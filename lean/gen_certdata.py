#!/usr/bin/env python3
"""Write lean/CertData.lean: the certificate as integers (scaled by 10^6), with an exact sum-of-squares witness for
every site matrix.

For each site y, from the exact LDL^T factorisation G_y = sum_k d_k l_k l_k^T we write integer vectors u_k, positive
integer weights c_k and a positive integer S with S * Gint = sum_k c_k u_k u_k^T, where Gint = 10^6 G_y. Lean checks
this identity entry by entry, so the witness is only a hint: nothing about how it was found is trusted.

Usage: python3 lean/gen_certdata.py [data/cert4d_h14.42.npy]
"""
import itertools
import math
import os
import sys
from fractions import Fraction

import numpy as np

DEN = 10 ** 6
here = os.path.dirname(os.path.abspath(__file__))
cert = np.load(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "data", "cert4d_h14.42.npy"),
               allow_pickle=True).item()
sites = sorted(itertools.product(range(2), repeat=4))


def to_int(v):
    q = Fraction(v) * DEN
    assert q.denominator == 1, v
    return int(q)


def sos(G):
    n = len(G)
    M = [[Fraction(v) for v in r] for r in G]
    L = [[Fraction(int(i == j)) for j in range(n)] for i in range(n)]
    dg = []
    for j in range(n):
        dj = M[j][j] - sum(L[j][k] ** 2 * dg[k] for k in range(j))
        assert dj > 0
        dg.append(dj)
        for i in range(j + 1, n):
            L[i][j] = (M[i][j] - sum(L[i][k] * L[j][k] * dg[k] for k in range(j))) / dj
    us, ws = [], []
    for k in range(n):
        col = [L[i][k] for i in range(n)]
        q = math.lcm(*(c.denominator for c in col))
        us.append([int(c * q) for c in col])
        ws.append(dg[k] * DEN / q ** 2)
    S = math.lcm(*(w.denominator for w in ws))
    cs = [int(w * S) for w in ws]
    Gi = [[to_int(v) for v in r] for r in G]
    for i in range(n):
        for j in range(n):
            assert S * Gi[i][j] == sum(c * u[i] * u[j] for c, u in zip(cs, us))
    return Gi, S, cs, us


lst = lambda xs: "[" + ", ".join(str(x) for x in xs) + "]"
out = ["/- Generated by gen_certdata.py from data/cert4d_h14.42.npy. Do not edit. -/", "",
       "/-- site matrices, scaled by 10^6, sites in lexicographic order. -/"]
Gs, Ss, Cs, Us = [], [], [], []
for y in sites:
    Gi, S, cs, us = sos(cert["G"][y])
    Gs.append(Gi), Ss.append(S), Cs.append(cs), Us.append(us)
out.append("def certG : List (List (List Int)) := [\n  " + ",\n  ".join(lst(lst(r) for r in g) for g in Gs) + "]")
out.append("/-- sum-of-squares witnesses: S * G = sum_k c_k u_k u_k^T. -/")
out.append("def certS : List Int := " + lst(Ss))
out.append("def certC : List (List Int) := [\n  " + ",\n  ".join(lst(c) for c in Cs) + "]")
out.append("def certU : List (List (List Int)) := [\n  " + ",\n  ".join(lst(lst(u) for u in us) for us in Us) + "]")
# plaquette weights, plaquettes in the order (x lexicographic, then (mu, nu) with mu < nu), positions 0..3
A = []
for a in cert["A"]:
    A.append([to_int(a[i]) if i in a else 0 for i in range(4)])
out.append("/-- plaquette weights a_{p,r}, scaled by 10^6, 0 at the fixed position. -/")
out.append("def certA : List (List Int) := [\n  " + ",\n  ".join(lst(r) for r in A) + "]")
out.append(f"/-- h, scaled by 10^6. -/\ndef certH : Int := {to_int(cert['h'])}")
open(os.path.join(here, "CertData.lean"), "w").write("\n".join(out) + "\n")
print("wrote CertData.lean:", len(Gs), "sites,", len(A), "plaquettes, h =", to_int(cert["h"]), "/ 10^6")
